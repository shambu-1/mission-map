# ---------- Missions ----------
class MissionIn(BaseModel):
    title: str = Field(min_length=1, max_length=120)
    description: str | None = Field(default=None, max_length=2000)
    type: MissionType = "side"
    category: Category = "explore"
    lat: float | None = Field(default=None, ge=-90, le=90)
    lng: float | None = Field(default=None, ge=-180, le=180)
    place_name: str | None = Field(default=None, max_length=255)
    radius_m: int = Field(default=100, ge=50, le=500)
    dwell_min: int = Field(default=0, ge=0, le=240)
    proof_required: bool = False
    deadline: datetime | None = None
    story_id: int | None = None
    chapter_no: int | None = Field(default=None, ge=1)
    visibility: Visibility = "private"
    verifier_id: int | None = None

    @field_validator("type")
    @classmethod
    def no_manual_daily(cls, v):
        if v == "daily":
            raise ValueError("daily missions are generated by the app")
        return v


